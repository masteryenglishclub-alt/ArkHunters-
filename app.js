const CAT_COLORS={dinos:"#2e7d4f",structures:"#7a5c2e",resources:"#6b6b6b",kits:"#2f6db5",engrams:"#6b3fa0",saddles:"#a0522d",bps:"#1e6f8c",special:"#b8860b"};
function slug(n){return n.toLowerCase().replace(/[^a-z0-9]+/g,"-").replace(/^-|-$/g,"")}
function badge(n,cat){
  const ini=n.split(/\s+/).filter(w=>/[A-Za-z]/.test(w)).slice(0,2).map(w=>w[0].toUpperCase()).join("");
  const c=CAT_COLORS[cat]||"#444";
  const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="88" height="88"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${c}"/><stop offset="1" stop-color="#0a0f16"/></linearGradient></defs><rect width="88" height="88" rx="14" fill="url(#g)"/><text x="44" y="56" font-family="Arial" font-weight="700" font-size="34" text-anchor="middle" fill="#fff">${ini}</text></svg>`;
  return "data:image/svg+xml;utf8,"+encodeURIComponent(svg);
}
function setIcon(img,n,cat){
  img.loading="lazy";
  img.onerror=()=>{img.onerror=null;img.src=badge(n,cat)};
  img.src="assets/items/"+slug(n)+".png";
}
